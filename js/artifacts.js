// ─── Helpers ───────────────────────────────────────────────────────────────────

function imgHTML(a) {
  if (a.imageUrl) {
    return `<img src="${a.imageUrl}" alt="${a.title}" loading="lazy"
              onerror="this.style.display='none';this.nextElementSibling.style.display='flex'">
            <div class="symbol-fallback" style="display:none">${a.symbol}</div>`;
  }
  return `<div class="symbol-fallback">${a.symbol}</div>`;
}

function cardHTML(a) {
  return `<article class="artifact-card" data-id="${a.id}" tabindex="0" role="button"
      aria-label="Open details for ${a.title}" style="--tone1:${a.tone1};--tone2:${a.tone2}">
    <div class="card-visual">
      ${imgHTML(a)}
    </div>
    <div class="card-body">
      <span class="tag">${a.era} · ${a.date}</span>
      <h3>${a.title}</h3>
      <p>${a.description}</p>
    </div>
  </article>`;
}

// ─── Related Artifacts ────────────────────────────────────────────────────────

function getRelated(artifact, n = 3) {
  return window.artifacts
    .filter(a => a.id !== artifact.id)
    .map(a => {
      let score = 0;
      if (a.era === artifact.era) score += 3;
      if (a.region === artifact.region) score += 2;
      if (a.medium && artifact.medium && a.medium.split(" ")[0] === artifact.medium.split(" ")[0]) score += 1;
      return { a, score };
    })
    .sort((x, y) => y.score - x.score)
    .slice(0, n)
    .map(x => x.a);
}

